def display_method(method):

    st.markdown(f"#### {method['name']}")

    st.caption(method["category"])

    st.markdown("**치료 목적**")
    st.write(method["purpose"])

    st.markdown("**구체적인 치료 방법**")
    st.write(method["method"])

    st.markdown("**주요 특징**")

    for feature in method["features"]:
        st.markdown(f"- {feature}")

    st.markdown("**한계 및 고려할 점**")

    for limitation in method["limitations"]:
        st.markdown(f"- {limitation}")


def make_comparison_dataframe(methods):

    rows = []

    for method in methods:

        rows.append({
            "치료 방법": method["name"],
            "치료 유형": method["category"],
            "치료 목적": method["purpose"],
            "구체적인 방법": method["method"],
            "주요 특징": " / ".join(method["features"]),
            "한계 및 고려할 점": " / ".join(method["limitations"])
        })

    return pd.DataFrame(rows)


def display_disease_detail(disease, key_prefix):

    data = TREATMENT_DATA[disease]

    st.markdown(f"### 🩺 {disease}")

    st.write(data["summary"])

    st.divider()

    st.subheader("치료 방법 비교")

    methods = data["methods"]

    columns = st.columns(
        min(len(methods), 2)
    )

    for index, method in enumerate(methods):

        with columns[index % 2]:

            with st.container(border=True):
                display_method(method)

    st.divider()

    st.subheader("핵심 비교표")

    st.dataframe(
        make_comparison_dataframe(methods),
        use_container_width=True,
        hide_index=True
    )

    st.divider()

    st.subheader("치료 방법 상세 설명")

    selected_method = st.selectbox(
        "자세히 알아볼 치료 방법을 선택하세요.",
        [method["name"] for method in methods],
        key=f"{key_prefix}_detail"
    )

    selected_data = next(
        method for method in methods
        if method["name"] == selected_method
    )

    with st.container(border=True):
        display_method(selected_data)

    if data["sources"]:

        st.divider()

        with st.expander("참고 자료 및 출처"):

            for source in data["sources"]:
                st.markdown(f"- {source}")


