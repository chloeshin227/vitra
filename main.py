# =========================================================
# 의료 정보 분석 함수
# =========================================================

def analyze_medical_info(text):
    """
    입력된 검사/진료 정보에서
    질환 관련 키워드를 찾아 질환과
    관련 신체 부위를 반환한다.
    """

    text = text.strip()

    # 긴 표현부터 검사하여
    # '충수돌기염' 같은 표현을 정확하게 인식한다.
    all_keywords = []

    for disease, information in DISEASE_DATA.items():

        for keyword in information["keywords"]:

            all_keywords.append(
                (len(keyword), keyword, disease, information)
            )

    # 긴 키워드부터 검사
    all_keywords.sort(
        key=lambda x: x[0],
        reverse=True
    )

    for _, keyword, disease, information in all_keywords:

        if keyword in text:

            return {
                "disease": disease,
                "organ": information["organ"],
                "body_part": information["body_part"]
            }

    return None


