# =========================================================
# 신체 시각화 함수
# =========================================================

def create_body_visualization(result):

    fig = go.Figure()

    # -----------------------------------------------------
    # 머리
    # -----------------------------------------------------

    fig.add_shape(
        type="circle",
        x0=-0.35,
        x1=0.35,
        y0=5.05,
        y1=5.75,
        line=dict(
            color="black",
            width=2
        ),
        fillcolor="white"
    )

    # -----------------------------------------------------
    # 몸통
    # 기존 알록달록한 디자인 유지
    # -----------------------------------------------------

    fig.add_shape(
        type="rect",
        x0=-0.45,
        x1=0.45,
        y0=1.9,
        y1=4.8,
        line=dict(width=0),
        fillcolor="#1976D2"
    )

    # -----------------------------------------------------
    # 왼쪽 팔
    # -----------------------------------------------------

    fig.add_trace(
        go.Scatter(
            x=[-0.35, -1.05],
            y=[4.45, 2.8],
            mode="lines",
            line=dict(
                width=28,
                color="#64B5F6"
            ),
            hoverinfo="skip",
            showlegend=False
        )
    )

    # -----------------------------------------------------
    # 오른쪽 팔
    # -----------------------------------------------------

    fig.add_trace(
        go.Scatter(
            x=[0.35, 1.05],
            y=[4.45, 2.8],
            mode="lines",
            line=dict(
                width=28,
                color="#FF2028"
            ),
            hoverinfo="skip",
            showlegend=False
        )
    )

    # -----------------------------------------------------
    # 왼쪽 다리
    # -----------------------------------------------------

    fig.add_trace(
        go.Scatter(
            x=[-0.20, -0.65],
            y=[1.9, 0.1],
            mode="lines",
            line=dict(
                width=32,
                color="#FF9E9E"
            ),
            hoverinfo="skip",
            showlegend=False
        )
    )

    # -----------------------------------------------------
    # 오른쪽 다리
    # -----------------------------------------------------

    fig.add_trace(
        go.Scatter(
            x=[0.20, 0.65],
            y=[1.9, 0.1],
            mode="lines",
            line=dict(
                width=32,
                color="#26A69A"
            ),
            hoverinfo="skip",
            showlegend=False
        )
    )

    # -----------------------------------------------------
    # 분석된 장기 위치
    # -----------------------------------------------------

    organ = result["organ"]

    x, y = ORGAN_POSITION.get(
        organ,
        (0.0, 3.0)
    )

    # -----------------------------------------------------
    # 장기 강조 표시
    #
    # Scatter 대신 Shape + Annotation을 사용해서
    # 몸통 위에 확실하게 보이도록 함
    # -----------------------------------------------------

    marker_size = 0.22

    fig.add_shape(
        type="circle",

        x0=x - marker_size,
        x1=x + marker_size,

        y0=y - marker_size,
        y1=y + marker_size,

        fillcolor="#69E89A",

        line=dict(
            color="#FFFFFF",
            width=3
        )
    )

    # -----------------------------------------------------
    # 장기 이름
    # -----------------------------------------------------

    fig.add_annotation(
        x=x + 0.32,
        y=y,

        text=f"<b>{organ}</b>",

        showarrow=False,

        font=dict(
            size=15,
            color="#5F6B7A"
        ),

        xanchor="left",
        yanchor="middle"
    )

    # -----------------------------------------------------
    # 그래프 설정
    # -----------------------------------------------------

    fig.update_layout(

        height=600,

        xaxis=dict(
            visible=False,
            range=[-1.4, 1.4],
            fixedrange=True
        ),

        yaxis=dict(
            visible=False,
            range=[-0.2, 6.0],
            fixedrange=True
        ),

        margin=dict(
            l=0,
            r=0,
            t=10,
            b=10
        ),

        plot_bgcolor="white",
        paper_bgcolor="white",

        dragmode=False
    )

    return fig


