# =========================================================

def analyze_medical_info(text):

    text = text.strip()

    if not text:
        return None

    all_keywords = []

    for disease, information in DISEASE_DATA.items():

        for keyword in information["keywords"]:

            all_keywords.append(
                (
                    len(keyword),
                    keyword,
                    disease,
                    information
                )
            )

    # 긴 키워드를 먼저 검사
    all_keywords.sort(
        key=lambda x: x[0],
        reverse=True
    )

    for _, keyword, disease, information in all_keywords:

        if keyword in text:

            return {
                "disease": disease,
                "organ": information["organ"],
                "body_part": information["body_part"]
            }

    return None


