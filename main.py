def create_surgery_visualization(result):

    disease = result["disease"]

    information = DISEASE_DATA[disease]

    steps = information["surgery_steps"]

    fig = go.Figure()

    # 단계별 위치
    positions = []

    for i in range(len(steps)):

        positions.append(
            (i + 1, 0)
        )

    # 연결선
    for i in range(len(positions) - 1):

        x1 = positions[i][0]
        x2 = positions[i + 1][0]

        fig.add_trace(
            go.Scatter(
                x=[x1, x2],
                y=[0, 0],
                mode="lines",
                line=dict(
                    width=4
                ),
                hoverinfo="skip",
                showlegend=False
            )
        )

    # 단계 원
    for i, step in enumerate(steps):

        x = i + 1

        fig.add_trace(
            go.Scatter(
                x=[x],
                y=[0],
                mode="markers+text",

                marker=dict(
                    size=45
                ),

                text=[str(i + 1)],

                textposition="middle center",

                textfont=dict(
                    size=16
                ),

                hovertemplate=(
                    f"<b>{i + 1}단계</b><br>"
                    f"{step}"
                    "<extra></extra>"
                ),

                showlegend=False
            )
        )

        fig.add_annotation(
            x=x,
            y=-0.45,
            text=step,
            showarrow=False,
            xanchor="center",
            yanchor="top",
            font=dict(
                size=12
            ),
            width=150
        )

    fig.update_layout(

        height=350,

        title=information["surgery_title"],

        xaxis=dict(
            visible=False,
            range=[0.5, len(steps) + 0.5]
        ),

        yaxis=dict(
            visible=False,
            range=[-1.8, 0.8]
        ),

        margin=dict(
            l=20,
            r=20,
            t=60,
            b=20
        ),

        plot_bgcolor="white",
        paper_bgcolor="white",

        hovermode="closest"
    )

    return fig


